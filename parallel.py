import multiprocessing
import multiprocessing.pool as mp_pool
import sys
import signal
import logging
from contextlib import contextmanager

LOGGER = logging.getLogger(__name__)


def main_loop(experiment_type, experiment_settings, n_workers, mainloop_fcn):
    """
    Wrapper for main-loop simulation function.
    """
    # Instantiate experiment before making fork.
    # This will leverage copy-on-write memory management
    global __EXP_INSTANCE
    __EXP_INSTANCE = experiment_type(experiment_settings)

    worker_contexts = __EXP_INSTANCE.prepare_workers(n_workers)
    n_workers = len(worker_contexts)

    batch_size = getattr(__EXP_INSTANCE, 'batch_size', 1)
    with init_pool(worker_contexts) as pool:
        mainloop_fcn(pool, batch_size=batch_size)


def schedule_tasks(snr_db, n_tasks, batch_size, pool):
    """
    Schedule n_tasks independent tasks; each task runs batch_size trials.
    """
    return pool.map_async(
        single_run,
        [(snr_db, batch_size)] * n_tasks
    )


@contextmanager
def init_pool(worker_contexts):
    """
    Initialize the parallel pool from per-worker WorkerContext entries.
    """
    n_workers = len(worker_contexts)
    LOGGER.info('Initializing pool of %d workers.', n_workers)
    # Use 'fork' to leverage copy-on-write memory management
    ctx = multiprocessing.get_context('fork')
    worker_queue = ctx.Queue()
    for context in worker_contexts:
        worker_queue.put(context)
    pool = ctx.Pool(
        processes=n_workers,
        initializer=init_worker,
        initargs=(worker_queue,)
    )

    try:
        yield pool
    except BaseException:
        LOGGER.warning('Aborting the pool.')
        _abort_pool(pool)
        raise
    else:
        LOGGER.info('Closing the pool.')
        try:
            pool.close()
            pool.join()
        except BaseException:
            LOGGER.warning('Aborting the pool during shutdown.')
            _abort_pool(pool)
            raise
        LOGGER.info('Pool closed.')


def _abort_pool(pool):
    """
    Stop the pool without relying on multiprocessing.Pool.terminate().

    On Linux, Pool.terminate() can block while its helper threads drain the
    task queue. Avoid that path: stop the helper threads, send SIGTERM directly
    to the workers, and cancel the pool finalizer so interpreter shutdown does
    not wait for the pool again.
    """
    pool._state = mp_pool.TERMINATE
    pool._worker_handler._state = mp_pool.TERMINATE
    pool._task_handler._state = mp_pool.TERMINATE
    pool._result_handler._state = mp_pool.TERMINATE

    workers = list(pool._pool)
    for worker in workers:
        if worker.is_alive():
            worker.terminate()
    for worker in workers:
        worker.join(timeout=2)
    for worker in workers:
        if worker.is_alive():
            LOGGER.error('Worker %s did not stop after SIGTERM.', worker.pid)

    # The finalizer would call Pool._terminate_pool() again at interpreter
    # shutdown; workers are already gone, so cancel it.
    pool._terminate.cancel()


# Below are worker-related methods (All methods are static to avoid serialization)
def single_run(args):
    """
    This is a single test wrapper
    In the case of crash, stacktrace will be written to file
    :param args: required arguments tuple
    """
    snr_db, batch_size = args
    return __EXP_INSTANCE.run_batch(snr_db, batch_size)


def sighandler(_, __):
    """
    Signal handler for worker
    In the case of KeyboardInterrupt, hide a large stacktrace generated by workers.
    Just silently exit
    """
    sys.exit(1)


def init_worker(worker_queue):
    """
    Initialize pool worker with its independent RNG and optional experiment
    data (for example a device index).
    """
    signal.signal(signal.SIGINT, sighandler)
    # The parent converts SIGTERM into a cleanup exception. Workers must keep
    # the default behavior so pool.terminate() actually stops them.
    signal.signal(signal.SIGTERM, signal.SIG_DFL)

    try:
        worker_context = worker_queue.get()
        worker_queue.close()
    except OSError:
        # If some worker pool_crashed, multiprocessing.Pool() will try to
        # re-initialize a worker. It cannot receive a proper context in this case.
        sys.exit(1)

    # The experiment owns worker-context semantics.
    __EXP_INSTANCE.init_worker(worker_context)
